"""
Prepare a standard 2-class YOLOv8 detection dataset from the raw CCTV
shoplifting download.

Why this exists: every box in the raw data/CCTV_Shoplifting_Dataset/labels/*.txt
has class_id 0 (see src/data/eda.py's docstring) - those labels are YOLO
*pose* format, and the only class they encode is "person". The actual
shoplifting / not_shoplifting signal lives one level up, in each source
video's VLM-labels/*.json ("is_anomaly_sequence"). A detector fine-tuned
on the boxes exactly as shipped could only ever learn "there's a person
here" - never shoplifting vs. not - so it wouldn't do what this project
is actually meant to do.

This script fixes that by re-deriving each frame's class from the same
VLM-labels join src/utils/dataset_discovery.py uses, dropping the 17
keypoint triplets (this project's YOLO half is a plain detector, not a
pose model), and writing out a plain 2-class YOLO detection dataset:
    0 = not_shoplifting_person
    1 = shoplifting_person

Train/val is split by *source video*, not by frame: frames are sampled
every 3rd frame from the same 8 source videos, so a per-frame random
split would land near-duplicate consecutive frames from one video on
both sides of the split (leakage) and make validation numbers meaningless.
Instead, one whole video per class is held out for validation.

Run after `python src/data/download_dataset.py` has populated data/.
Writes to outputs/yolo_dataset/ (gitignored, regenerated by re-running
this script): images/{train,val}/, labels/{train,val}/, and a data.yaml
ready for `ultralytics` training.
"""

import shutil
import sys
from collections import Counter
from pathlib import Path

import yaml
from tqdm import tqdm

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from src.utils.dataset_discovery import (  # noqa: E402
    find_annotation_files,
    find_images_dir,
    labels_dir_for_images,
    list_images,
    load_vlm_video_labels,
    parse_yolo_label,
    video_stem_for_image,
)

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = PROJECT_ROOT / "data"
OUTPUT_DIR = PROJECT_ROOT / "outputs" / "yolo_dataset"

CLASS_NAMES = {0: "not_shoplifting_person", 1: "shoplifting_person"}


def choose_val_videos(video_labels: dict[str, dict]) -> set[str]:
    """Hold out one whole video per class for validation, so validation
    never sees near-duplicate frames from a video it trained on."""
    by_class: dict[bool, list[str]] = {True: [], False: []}
    for video_stem, record in video_labels.items():
        by_class[bool(record.get("is_anomaly_sequence"))].append(video_stem)

    val_videos = set()
    for videos in by_class.values():
        if videos:
            val_videos.add(sorted(videos)[-1])
    return val_videos


def write_remapped_label(src_label: Path, dest_label: Path, new_cls_id: int) -> None:
    boxes = parse_yolo_label(src_label)
    lines = [f"{new_cls_id} {xc:.6f} {yc:.6f} {w:.6f} {h:.6f}" for _, xc, yc, w, h in boxes]
    dest_label.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    if not DATA_DIR.exists() or not any(DATA_DIR.iterdir()):
        raise SystemExit("data/ is empty. Run `python src/data/download_dataset.py` first.")

    images_dir = find_images_dir(DATA_DIR)
    if images_dir is None:
        raise SystemExit("Could not find an images/ directory under data/.")
    labels_dir = labels_dir_for_images(images_dir)

    vlm_files = find_annotation_files(DATA_DIR)
    video_labels = load_vlm_video_labels(vlm_files) if vlm_files else {}
    if not video_labels:
        raise SystemExit(
            "No VLM-labels JSON found under data/ - can't derive shoplifting / "
            "not_shoplifting classes without it."
        )

    val_videos = choose_val_videos(video_labels)
    print(f"Validation videos (held out whole, to avoid frame-level leakage): {sorted(val_videos)}")
    print(f"Train videos: {sorted(set(video_labels) - val_videos)}")

    for split in ("train", "val"):
        (OUTPUT_DIR / "images" / split).mkdir(parents=True, exist_ok=True)
        (OUTPUT_DIR / "labels" / split).mkdir(parents=True, exist_ok=True)

    split_counts = {"train": 0, "val": 0}
    class_counts = {"train": Counter(), "val": Counter()}
    skipped = 0

    for img_path in tqdm(list_images(images_dir), desc="Preparing YOLO dataset"):
        record = video_labels.get(video_stem_for_image(img_path))
        if record is None:
            skipped += 1
            continue

        video_stem = video_stem_for_image(img_path)
        new_cls_id = 1 if record.get("is_anomaly_sequence") else 0
        split = "val" if video_stem in val_videos else "train"

        shutil.copy2(img_path, OUTPUT_DIR / "images" / split / img_path.name)
        write_remapped_label(
            labels_dir / (img_path.stem + ".txt"),
            OUTPUT_DIR / "labels" / split / (img_path.stem + ".txt"),
            new_cls_id,
        )

        split_counts[split] += 1
        class_counts[split][CLASS_NAMES[new_cls_id]] += 1

    if skipped:
        print(f"Skipped {skipped} image(s) with no matching VLM-labels entry.")

    data_yaml = {
        "path": str(OUTPUT_DIR.resolve()),
        "train": "images/train",
        "val": "images/val",
        "names": CLASS_NAMES,
    }
    (OUTPUT_DIR / "data.yaml").write_text(yaml.dump(data_yaml, sort_keys=False), encoding="utf-8")

    print(f"\nWrote {sum(split_counts.values())} images to {OUTPUT_DIR}")
    for split in ("train", "val"):
        print(f"  {split}: {split_counts[split]} images, class counts: {dict(class_counts[split])}")
    print(f"\ndata.yaml written to {OUTPUT_DIR / 'data.yaml'}")
    print("Keypoints dropped - labels are now plain 2-class YOLO detection boxes.")


if __name__ == "__main__":
    main()
